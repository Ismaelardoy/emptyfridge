import type { AppOutletContext } from '@/app/ProtectedLayout';
import { useCreateRecoveryCode, useLogout, useRenameDisplayName } from '@/features/auth/hooks';
import { RecentAdditions } from '@/features/list/RecentAdditions';
import { useCurrentList } from '@/features/list/hooks';
import { Button } from '@/shared/ui/Button';
import { Card } from '@/shared/ui/Card';
import { Field } from '@/shared/ui/Field';
import { Modal } from '@/shared/ui/Modal';
import { Spinner } from '@/shared/ui/Spinner';
import type { HouseholdMemberDto } from '@emptyfridge/contracts';
import {
  Copy,
  Crown,
  LogOut,
  MessageCircle,
  Pencil,
  Share2,
  Smartphone,
  UserMinus,
  Users,
} from 'lucide-react';
import { type FormEvent, useCallback, useEffect, useRef, useState } from 'react';
import { useNavigate, useOutletContext } from 'react-router-dom';
import { toast } from 'sonner';
import { useHousehold, useRemoveMember, useRenameHousehold, useTransferOwnership } from './hooks';

export function HouseholdPage() {
  const { user } = useOutletContext<AppOutletContext>();
  const navigate = useNavigate();
  const household = useHousehold();
  const currentList = useCurrentList();
  const rename = useRenameHousehold();
  const renameDisplayName = useRenameDisplayName();
  const logout = useLogout();
  const removeMember = useRemoveMember();
  const transferOwnership = useTransferOwnership();

  const [renameOpen, setRenameOpen] = useState(false);
  const [householdName, setHouseholdName] = useState('');
  const [nameOpen, setNameOpen] = useState(false);
  const [displayName, setDisplayName] = useState('');
  const [removeTarget, setRemoveTarget] = useState<HouseholdMemberDto | null>(null);
  const [ownerTarget, setOwnerTarget] = useState<HouseholdMemberDto | null>(null);
  const [logoutOpen, setLogoutOpen] = useState(false);
  const createRecovery = useCreateRecoveryCode();
  const autoGenerated = useRef(false);
  const generateRecovery = useCallback(() => {
    createRecovery.mutate(undefined, {
      onError: (error) => toast.error(error.message),
    });
  }, [createRecovery]);

  // Si la identidad todavía no tiene código, se genera automáticamente.
  useEffect(() => {
    if (user.recoveryCode || autoGenerated.current) {
      return;
    }
    autoGenerated.current = true;
    generateRecovery();
  }, [user.recoveryCode, generateRecovery]);

  if (household.isLoading) {
    return <Spinner />;
  }

  if (household.isError || !household.data) {
    return (
      <div className="px-4 py-4">
        <h1 className="text-xl font-bold tracking-tight text-stone-900">Hogar</h1>
        <div className="mt-4 rounded-3xl bg-white p-6 text-center ring-1 ring-stone-200/70">
          <p className="text-sm font-semibold text-stone-700">No se pudo cargar el hogar</p>
          <p className="mt-1 text-xs text-stone-500">
            {household.error?.message ?? 'Inténtalo de nuevo.'}
          </p>
          <Button variant="secondary" className="mt-4" onClick={() => void household.refetch()}>
            Reintentar
          </Button>
        </div>
      </div>
    );
  }

  const { household: home, members } = household.data;
  const isOwner = user.household?.role === 'owner';
  const inviteUrl = `${window.location.origin}/join/${home.inviteCode}`;
  const canShare = typeof navigator !== 'undefined' && typeof navigator.share === 'function';

  const copyInvite = async () => {
    try {
      await navigator.clipboard.writeText(inviteUrl);
      toast.success('Enlace copiado');
    } catch {
      toast.error('No se pudo copiar el enlace');
    }
  };

  const shareOnWhatsApp = () => {
    const message = `¡Únete a la lista de la compra de ${home.name} en erfrigovacio! ${inviteUrl}`;
    window.open(
      `https://wa.me/?text=${encodeURIComponent(message)}`,
      '_blank',
      'noopener,noreferrer',
    );
  };

  const shareInvite = async () => {
    try {
      await navigator.share({
        title: 'Únete a nuestro hogar',
        text: 'Únete a nuestra lista de la compra',
        url: inviteUrl,
      });
    } catch {
      // El usuario ha cancelado el diálogo de compartir.
    }
  };

  const openRename = () => {
    setHouseholdName(home.name);
    setRenameOpen(true);
  };

  const submitRename = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const name = householdName.trim();
    if (!name) {
      return;
    }
    rename.mutate(name, { onSuccess: () => setRenameOpen(false) });
  };

  const openName = () => {
    setDisplayName(user.displayName);
    setNameOpen(true);
  };

  const submitName = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const name = displayName.trim();
    if (!name) {
      return;
    }
    if (name === user.displayName) {
      setNameOpen(false);
      return;
    }
    renameDisplayName.mutate(
      { displayName: name },
      {
        onSuccess: () => {
          setNameOpen(false);
          toast.success('Nombre actualizado');
        },
        onError: (error) => toast.error(error.message),
      },
    );
  };

  const signOut = () => {
    logout.mutate(undefined, {
      onSuccess: () => {
        setLogoutOpen(false);
        navigate('/join', { replace: true });
      },
      onError: (error) => toast.error(error.message),
    });
  };

  const copyRecovery = async () => {
    if (!user.recoveryCode) {
      return;
    }
    try {
      await navigator.clipboard.writeText(user.recoveryCode);
      toast.success('Código copiado');
    } catch {
      toast.error('No se pudo copiar el código');
    }
  };

  return (
    <div className="px-4 pt-4 pb-24 lg:pb-6">
      <h1 className="text-xl font-bold tracking-tight text-stone-900">Hogar</h1>
      <div className="mt-0.5 flex items-center gap-1.5">
        <p className="truncate text-xs text-stone-500">{home.name}</p>
        {isOwner ? (
          <button
            type="button"
            onClick={openRename}
            aria-label="Cambiar nombre del hogar"
            title="Cambiar nombre del hogar"
            className="flex h-11 w-11 shrink-0 items-center justify-center rounded-full bg-stone-100/70 text-stone-500 ring-1 ring-stone-200/60 transition-colors hover:bg-stone-200/60 hover:text-stone-700"
          >
            <Pencil className="h-5 w-5" />
          </button>
        ) : null}
      </div>

      <div className="mt-4 grid gap-4 md:grid-cols-2 2xl:grid-cols-3">
        <Card>
          <p className="text-[11px] font-bold uppercase tracking-[0.14em] text-stone-400">
            Invitar a quien quieras
          </p>
          <p
            data-testid="invite-code"
            className="mt-2 font-mono text-2xl font-bold tracking-[0.25em] text-stone-900"
          >
            {home.inviteCode}
          </p>
          <p className="mt-1 text-xs leading-5 text-stone-500">
            Comparte este enlace por WhatsApp. Quien lo abra entrará directamente en la lista, sin
            crear cuenta.
          </p>
          <div className="mt-4 space-y-2">
            <Button
              className="w-full bg-[#25D366] text-white hover:bg-[#1ebe5b] active:bg-[#199e4b]"
              onClick={shareOnWhatsApp}
            >
              <MessageCircle className="h-4 w-4" />
              Compartir por WhatsApp
            </Button>
            <div className="flex gap-2">
              <Button className="flex-1" variant="secondary" onClick={() => void copyInvite()}>
                <Copy className="h-4 w-4" />
                Copiar enlace
              </Button>
              {canShare ? (
                <Button variant="secondary" onClick={() => void shareInvite()}>
                  <Share2 className="h-4 w-4" />
                  Más opciones
                </Button>
              ) : null}
            </div>
          </div>
        </Card>

        <Card>
          <p className="text-[11px] font-bold uppercase tracking-[0.14em] text-stone-400">Tú</p>
          <div className="mt-2 flex items-center justify-between gap-3">
            <p className="truncate text-sm font-medium text-stone-800">{user.displayName}</p>
            <button
              type="button"
              onClick={openName}
              aria-label="Cambiar mi nombre"
              className="flex h-11 shrink-0 items-center gap-2 rounded-xl bg-stone-50 px-3 text-sm font-semibold text-stone-500 ring-1 ring-stone-200 transition-colors hover:bg-stone-100 hover:text-stone-700"
            >
              <Pencil className="h-4 w-4" />
              Cambiar
            </button>
          </div>
          <p className="mt-1 text-xs leading-5 text-stone-500">
            Te recordamos en este dispositivo. Sin cuenta ni contraseña. Puedes cambiar el nombre
            que verán los demás miembros.
          </p>
          <Button className="mt-3 w-full" variant="secondary" onClick={() => setLogoutOpen(true)}>
            <LogOut className="h-4 w-4" />
            Cerrar sesión en este dispositivo
          </Button>
        </Card>

        <Card>
          <p className="text-[11px] font-bold uppercase tracking-[0.14em] text-stone-400">
            Iniciar sesión en otro dispositivo
          </p>
          <p className="mt-2 text-sm font-medium text-stone-800">
            Un código guardable, sin cuenta ni PIN
          </p>
          <p className="mt-1 text-xs leading-5 text-stone-500">
            {user.recoveryCode
              ? 'Guárdalo en un sitio seguro. Es tu código de acceso a esta lista.'
              : createRecovery.isPending
                ? 'Generando tu código de acceso…'
                : 'No se pudo generar el código de acceso.'}
          </p>

          {user.recoveryCode ? (
            <div className="mt-4 space-y-2">
              <p
                data-testid="recovery-code"
                className="break-all rounded-2xl bg-stone-50 px-3 py-3 text-center font-mono text-lg font-bold tracking-[0.15em] text-stone-900 ring-1 ring-stone-200"
              >
                {user.recoveryCode}
              </p>
              <Button className="w-full" variant="secondary" onClick={() => void copyRecovery()}>
                <Copy className="h-4 w-4" />
                Copiar código
              </Button>
            </div>
          ) : createRecovery.isError ? (
            <Button
              className="mt-3 w-full"
              variant="secondary"
              loading={createRecovery.isPending}
              onClick={generateRecovery}
            >
              <Smartphone className="h-4 w-4" />
              Reintentar
            </Button>
          ) : null}
        </Card>
      </div>

      <section className="mt-6">
        <h2 className="mb-2 flex items-center gap-1.5 px-1 text-[11px] font-bold uppercase tracking-[0.14em] text-stone-400">
          <Users className="h-3.5 w-3.5" />
          Miembros ({members.length})
        </h2>
        <ul className="grid gap-2 md:grid-cols-2">
          {members.map((entry) => (
            <li
              key={entry.id}
              className="flex items-center gap-3 rounded-2xl bg-white p-3 ring-1 ring-stone-200/60"
            >
              <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-stone-100 text-sm font-bold text-stone-600">
                {entry.displayName.charAt(0).toUpperCase()}
              </span>
              <span className="min-w-0 flex-1">
                <span className="flex items-center gap-2 text-sm font-medium text-stone-800">
                  <span className="truncate">{entry.displayName}</span>
                  {entry.id === user.id ? (
                    <span className="text-xs font-normal text-stone-400">tú</span>
                  ) : null}
                </span>
                <span className="text-[11px] text-stone-400">
                  {entry.role === 'owner' ? 'Propietario' : 'Miembro'}
                </span>
              </span>
              {entry.id !== user.id ? (
                <>
                  {isOwner ? (
                    <button
                      type="button"
                      onClick={() => setOwnerTarget(entry)}
                      aria-label={`Hacer owner a ${entry.displayName}`}
                      title="Ceder la propiedad del hogar"
                      className="shrink-0 rounded-xl p-2 text-stone-300 transition-colors hover:bg-amber-50 hover:text-amber-600"
                    >
                      <Crown className="h-4 w-4" />
                    </button>
                  ) : null}
                  <button
                    type="button"
                    onClick={() => setRemoveTarget(entry)}
                    aria-label={`Expulsar a ${entry.displayName}`}
                    className="shrink-0 rounded-xl p-2 text-stone-300 transition-colors hover:bg-red-50 hover:text-red-500"
                  >
                    <UserMinus className="h-4 w-4" />
                  </button>
                </>
              ) : null}
            </li>
          ))}
        </ul>
      </section>

      <RecentAdditions entries={currentList.data?.recentAdditions ?? []} />

      <Modal
        open={logoutOpen}
        onClose={() => setLogoutOpen(false)}
        title="Cerrar sesión en este dispositivo"
      >
        <p className="text-sm leading-6 text-stone-600">
          Dejarás de usar esta lista en este dispositivo. La lista y los demás miembros siguen
          igual.
        </p>
        <p className="mt-3 rounded-2xl bg-amber-50 p-3 text-xs leading-5 text-amber-900 ring-1 ring-amber-200">
          Si esta es tu lista buena, asegúrate de tener guardado tu código de acceso. Sin él, este
          dispositivo perderá el acceso a tu identidad. También puedes pedir a otro miembro que te
          comparta el enlace del hogar.
        </p>
        <div className="mt-5 flex gap-2">
          <Button
            variant="secondary"
            className="flex-1"
            onClick={() => setLogoutOpen(false)}
            disabled={logout.isPending}
          >
            Cancelar
          </Button>
          <Button variant="danger" className="flex-1" loading={logout.isPending} onClick={signOut}>
            Cerrar sesión
          </Button>
        </div>
      </Modal>

      <Modal open={nameOpen} onClose={() => setNameOpen(false)} title="Tu nombre">
        <form onSubmit={submitName} className="space-y-3">
          <Field
            label="Nombre"
            value={displayName}
            onChange={(event) => setDisplayName(event.target.value)}
            maxLength={30}
            autoFocus
            required
            hint="Es el nombre que verán los demás miembros en la lista."
          />
          <div className="flex gap-2">
            <Button
              variant="secondary"
              className="flex-1"
              onClick={() => setNameOpen(false)}
              disabled={renameDisplayName.isPending}
            >
              Cancelar
            </Button>
            <Button
              type="submit"
              className="flex-1"
              loading={renameDisplayName.isPending}
              disabled={!displayName.trim()}
            >
              Guardar
            </Button>
          </div>
        </form>
      </Modal>

      <Modal open={renameOpen} onClose={() => setRenameOpen(false)} title="Nombre del hogar">
        <form onSubmit={submitRename} className="space-y-3">
          <Field
            label="Nombre del hogar"
            value={householdName}
            onChange={(event) => setHouseholdName(event.target.value)}
            maxLength={60}
            autoFocus
            required
          />
          <div className="flex gap-2">
            <Button
              variant="secondary"
              className="flex-1"
              onClick={() => setRenameOpen(false)}
              disabled={rename.isPending}
            >
              Cancelar
            </Button>
            <Button
              type="submit"
              className="flex-1"
              loading={rename.isPending}
              disabled={!householdName.trim()}
            >
              Guardar
            </Button>
          </div>
        </form>
      </Modal>

      <Modal
        open={ownerTarget !== null}
        onClose={() => setOwnerTarget(null)}
        title={ownerTarget ? `Ceder la propiedad a ${ownerTarget.displayName}` : 'Ceder propiedad'}
      >
        <p className="text-sm leading-6 text-stone-600">
          {ownerTarget?.displayName ?? 'Esa persona'} será el único propietario y tú pasarás a
          miembro. Solo los propietarios pueden renombrar el hogar y expulsar a otros.
        </p>
        <div className="mt-5 flex gap-2">
          <Button
            variant="secondary"
            className="flex-1"
            onClick={() => setOwnerTarget(null)}
            disabled={transferOwnership.isPending}
          >
            Cancelar
          </Button>
          <Button
            className="flex-1"
            loading={transferOwnership.isPending}
            onClick={() => {
              if (!ownerTarget) {
                return;
              }
              transferOwnership.mutate(ownerTarget.id, {
                onSuccess: () => setOwnerTarget(null),
              });
            }}
          >
            Ceder propiedad
          </Button>
        </div>
      </Modal>

      <Modal
        open={removeTarget !== null}
        onClose={() => setRemoveTarget(null)}
        title={removeTarget ? `Expulsar a ${removeTarget.displayName}` : 'Expulsar miembro'}
      >
        <p className="text-sm leading-6 text-stone-600">
          Dejará de tener acceso al hogar. Si vuelve a abrir el enlace de invitación, podrá entrar
          de nuevo.
        </p>
        <div className="mt-5 flex gap-2">
          <Button
            variant="secondary"
            className="flex-1"
            onClick={() => setRemoveTarget(null)}
            disabled={removeMember.isPending}
          >
            Cancelar
          </Button>
          <Button
            variant="danger"
            className="flex-1"
            loading={removeMember.isPending}
            onClick={() => {
              if (!removeTarget) {
                return;
              }
              removeMember.mutate(removeTarget.id, {
                onSuccess: () => setRemoveTarget(null),
              });
            }}
          >
            Expulsar
          </Button>
        </div>
      </Modal>
    </div>
  );
}
